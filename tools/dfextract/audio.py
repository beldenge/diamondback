_STEP_I8 = [b - 256 if b >= 128 else b for b in _STEP_SIZE]
_INDEX_I8 = [b - 256 if b >= 128 else b for b in _INDEX]


class AudioError(Exception):
    """Audio container could not be decoded."""


def i8(value: int) -> int:
    return ((value + 128) % 256) - 128


def audio_params(container: bytes) -> tuple[int, int, int]:
    """Return (codec_flag, hertz, uncompressed_size) from an audio container."""
    if len(container) < 40:
        raise AudioError("audio container too small for header")
    codec = struct.unpack_from("<h", container, 0x1A)[0]
    hertz = struct.unpack_from("<i", container, 28)[0]
    size = struct.unpack_from("<i", container, 36)[0]
    return codec, hertz, size


def decode_audio_container(container: bytes) -> tuple[bytes, int, int]:
    """Decode one audio container to PCM. Returns (pcm, hertz, sample_width)."""
    codec, hertz, size = audio_params(container)
    if size <= 0:
        raise AudioError(f"invalid uncompressed size {size}")
    if codec == 1:
        pcm = decode_v40(container, size)
        return pcm, hertz, 1
    pcm = decode_v41(container, size)
    return pcm, hertz, 2


def decode_v40(container: bytes, uncompressed_size: int) -> bytes:
    if struct.unpack_from("<i", container, 0)[0] != 0x00010000:
        raise AudioError("v40 container missing 00 00 01 00 signature")
    src = struct.unpack_from("<i", container, 44)[0]
    if src < 0 or src >= len(container):
        raise AudioError("v40 data offset out of range")

    out = bytearray(uncompressed_size)
    next_byte = i8(container[src])
    src += 1
    out[0] = (next_byte + 0x40) & 0xFF
    dst = 1
    prev = next_byte

    while dst < uncompressed_size:
        if src >= len(container):
            raise AudioError("v40 ran out of compressed input")
        next_byte = i8(container[src])
        src += 1
        raw = next_byte & 0xFF

        if raw & 0x80 == 0:
            out[dst] = (next_byte + 0x40) & 0xFF
            dst += 1
            prev = next_byte
        elif raw & 0x40 == 0:
            count = raw & 0x3F
            while True:
                if src >= len(container) or dst + 1 >= uncompressed_size:
                    raise AudioError("v40 mode-II overrun")
                sample = container[src]
                src += 1
                step = i8(prev + _STEP_I8[sample])
                index = i8(step + _INDEX_I8[sample])
                out[dst] = (step + 0x40) & 0xFF
                out[dst + 1] = (index + 0x40) & 0xFF
                dst += 2
                prev = index
                if count == 0:
                    break
                count -= 1
        else:
            count = (raw & 0x3F) + 1
            fill = (prev + 0x40) & 0xFF
            if dst + count > uncompressed_size:
                raise AudioError("v40 mode-III overrun")
            out[dst : dst + count] = bytes([fill]) * count
            dst += count

    if dst != uncompressed_size:
        raise AudioError(f"v40 length mismatch: wrote {dst}, expected {uncompressed_size}")
    return bytes(out)


def decode_v41(container: bytes, uncompressed_size: int) -> bytes:
    src = struct.unpack_from("<i", container, 44)[0]
    num_samples = uncompressed_size // 2
    if src < 0 or src + num_samples > len(container):
        raise AudioError("v41 data offset out of range")

    out = bytearray(uncompressed_size)
    current = 0
    for i in range(num_samples):
        input_byte = container[src + i]
        if input_byte & 0x80 == 0:
            delta = (input_byte << 9) & 0xFFFF
            if delta >= 0x8000:
                delta -= 0x10000
            delta >>= 4
            current = i16(current + delta)
        else:
            current = i16(input_byte << 9)
        struct.pack_into("<h", out, i * 2, current)
    return bytes(out)


def i16(value: int) -> int:
    value = ((value + 0x8000) % 0x10000) - 0x8000
    return value


def write_wav(path: Path, pcm: bytes, hertz: int, sample_width: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(sample_width)
        handle.setframerate(hertz)
        handle.writeframes(pcm)


def wav_from_container(path: Path, container: bytes) -> Path:
    pcm, hertz, width = decode_audio_container(container)
    write_wav(path, pcm, hertz, width)
    return path


def safe_wav_name(name: str) -> str:
    trimmed = name.replace("\\", "/").split("/")[-1].strip()
    return trimmed or "audio"
